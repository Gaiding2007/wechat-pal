const FALLBACK = [
  ['嗯，我在听。', '然后呢？'],
  ['这样啊。', '你当时是什么感觉？'],
  ['我懂。', '慢慢说，不着急。'],
  ['嗯嗯。', '这件事对你来说重要吗？'],
];

let counter = 0;

function pick(list) {
  if (!list.length) return [];
  counter += 1;
  return list[counter % list.length];
}

function demoReply(text, { persona = {} } = {}) {
  const value = String(text || '');
  const hit = GROUPS.find((g) => g.test.test(value));
  const lines = pick(hit ? hit.replies : FALLBACK).slice();
  return {
    text: lines.join('\n'),
    bubbles: lines,
    mock: true,
    personaName: persona.name || '',
  };
}

function demoCare() {
  const lines = [
    ['在忙吗？', '突然想起你，过来问一句。'],
    ['刚看到窗外天挺好的。', '你今天出门了吗？'],
    ['嗯，没什么事。', '就是想说一声，我在。'],
  ];
  return pick(lines).slice();
}

